#!/usr/bin/env node
/*
 * pnpm postman:export [openapi.json] [output dir]
 *
 * Turns the OpenAPI document (`pnpm openapi:export`, run first by the package script) into a
 * Postman collection (v2.1) and a local environment, in ./postman (git-ignored, regenerate it):
 *   - one folder per Swagger tag, one request per operation, named by its summary;
 *   - JSON bodies filled from the schema examples; path and query parameters as Postman variables;
 *   - auth as the API declares it: bearer `{{accessToken}}` for signed-in routes, `x-api-key:
 *     {{apiKey}}` for machine routes, none for public ones;
 *   - every response carrying `data.accessToken` (sign up, sign in, refresh, OTP) stores the tokens,
 *     so "Auth › Sign up" or "Sign in" once authorises every other request;
 *   - `X-Timezone: {{timeZone}}` sent on every request.
 * No dependencies: the document is generated by this app, so the converter only handles what it
 * produces.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const input = resolve(process.argv[2] ?? 'openapi.json');
const outDir = resolve(process.argv[3] ?? 'postman');
const doc = JSON.parse(readFileSync(input, 'utf8'));
const pkg = JSON.parse(readFileSync(resolve('package.json'), 'utf8'));
const name = pkg.name;

// ── Variables (collection defaults; the environment file overrides per environment) ──
const VARIABLES = {
  baseUrl: 'http://localhost:3000',
  email: 'ada@example.com',
  password: 'correct-horse-42',
  timeZone: 'UTC',
  accessToken: '',
  refreshToken: '',
  apiKey: '',
};

// ── Example values from schemas ────────────────────────────────────────────────
const ref = (schema) => {
  let s = schema;
  while (s?.$ref)
    s = s.$ref
      .split('/')
      .slice(1)
      .reduce((node, key) => node[key], doc);
  return s ?? {};
};

/** Field names whose value comes from a variable, so requests chain without editing. */
const BY_NAME = {
  email: '{{email}}',
  password: '{{password}}',
  currentPassword: '{{password}}',
  refreshToken: '{{refreshToken}}',
  timeZone: '{{timeZone}}',
};

function example(schema, field, depth = 0) {
  const s = ref(schema);
  if (field && BY_NAME[field]) return BY_NAME[field];
  if (s.example !== undefined) return s.example;
  if (s.default !== undefined) return s.default;
  if (s.enum?.length) return s.enum[0];
  if (s.allOf) return Object.assign({}, ...s.allOf.map((part) => example(part, field, depth)));
  if (s.oneOf || s.anyOf) return example((s.oneOf ?? s.anyOf)[0], field, depth);
  if (depth > 6) return null;
  switch (s.type) {
    case 'object': {
      const required = new Set(s.required ?? []);
      const body = {};
      // Required fields always; optional ones only when the schema shows an example of them.
      for (const [key, prop] of Object.entries(s.properties ?? {})) {
        const p = ref(prop);
        if (required.has(key) || p.example !== undefined) body[key] = example(prop, key, depth + 1);
      }
      return body;
    }
    case 'array':
      return [example(s.items, undefined, depth + 1)];
    case 'integer':
    case 'number':
      return s.minimum ?? 1;
    case 'boolean':
      return false;
    case 'string':
      if (s.format === 'date-time') return '2026-01-01T09:00:00.000Z';
      if (s.format === 'email') return '{{email}}';
      if (s.format === 'uri' || /url$/i.test(field ?? '')) return 'https://example.com';
      if (/^[a-z]*phone/i.test(field ?? '')) return '+14155550123';
      if (/Ids?$/.test(field ?? '')) return '000000000000000000000000';
      return field ? `${field} value` : 'string';
    default:
      return null;
  }
}

// ── Requests ───────────────────────────────────────────────────────────────────
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

function request(path, method, op) {
  const params = (op.parameters ?? []).map((p) => ({ ...ref(p), schema: ref(ref(p).schema) }));
  const segments = path
    .split('/')
    .filter(Boolean)
    .map((part) => part.replace(/^\{(.+)\}$/, ':$1'));
  const query = params
    .filter((p) => p.in === 'query')
    .map((p) => ({
      key: p.name,
      value: String(p.example ?? p.schema.example ?? p.schema.default ?? ''),
      description: p.description,
      disabled: !p.required,
    }));
  const variable = params
    .filter((p) => p.in === 'path')
    .map((p) => ({ key: p.name, value: '', description: p.description ?? `${p.name} (required)` }));

  const security = op.security?.[0] ? Object.keys(op.security[0])[0] : null;
  const auth =
    security === 'bearer'
      ? undefined // inherits the collection's bearer {{accessToken}}
      : security === 'apiKey'
        ? {
            type: 'apikey',
            apikey: [
              { key: 'key', value: 'x-api-key', type: 'string' },
              { key: 'value', value: '{{apiKey}}', type: 'string' },
              { key: 'in', value: 'header', type: 'string' },
            ],
          }
        : { type: 'noauth' };

  const json = op.requestBody?.content?.['application/json'];
  const header = json ? [{ key: 'Content-Type', value: 'application/json' }] : [];
  const queryString = query
    .filter((q) => !q.disabled)
    .map((q) => `${q.key}=${q.value}`)
    .join('&');

  return {
    name: op.summary ?? op.operationId,
    request: {
      method: method.toUpperCase(),
      header,
      ...(auth ? { auth } : {}),
      ...(json
        ? {
            body: {
              mode: 'raw',
              raw: JSON.stringify(example(json.schema), null, 2),
              options: { raw: { language: 'json' } },
            },
          }
        : {}),
      url: {
        raw: `{{baseUrl}}/${segments.join('/')}${queryString ? `?${queryString}` : ''}`,
        host: ['{{baseUrl}}'],
        path: segments,
        ...(query.length ? { query } : {}),
        ...(variable.length ? { variable } : {}),
      },
      description: [op.description, op.operationId && `Operation id: \`${op.operationId}\``]
        .filter(Boolean)
        .join('\n\n'),
    },
  };
}

const folders = new Map();
for (const [path, ops] of Object.entries(doc.paths)) {
  for (const method of METHODS) {
    const op = ops[method];
    if (!op) continue;
    const tag = op.tags?.[0] ?? 'Other';
    if (!folders.has(tag)) folders.set(tag, []);
    folders.get(tag).push(request(path, method, op));
  }
}

// Versioned twins (v1 and v2 of one route) share a summary: name them apart.
for (const items of folders.values()) {
  const counts = new Map();
  for (const item of items) counts.set(item.name, (counts.get(item.name) ?? 0) + 1);
  for (const item of items) {
    const version = item.request.url.path.find((part) => /^v\d+$/.test(part));
    if (counts.get(item.name) > 1 && version) item.name = `${item.name} (${version})`;
  }
}

// ── Collection-level scripts ───────────────────────────────────────────────────
const PRE_REQUEST = ["pm.request.headers.upsert({ key: 'X-Timezone', value: pm.variables.get('timeZone') || 'UTC' });"];
const AFTER_RESPONSE = [
  '// Keeps the tokens of the last sign up / sign in / refresh, so every request is authorised.',
  'try {',
  '  const data = pm.response.json().data;',
  "  if (data && data.accessToken) pm.collectionVariables.set('accessToken', data.accessToken);",
  "  if (data && data.refreshToken) pm.collectionVariables.set('refreshToken', data.refreshToken);",
  '} catch (e) {',
  '  // Not JSON (204, health text): nothing to keep.',
  '}',
];

const collection = {
  info: {
    name: `${name} API`,
    description: `${doc.info.description}\n\nGenerated by \`pnpm postman:export\` from the OpenAPI document. Run **Auth › Sign up** (or **Sign in**) first: the tokens are stored and used by every request.`,
    schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
  },
  auth: { type: 'bearer', bearer: [{ key: 'token', value: '{{accessToken}}', type: 'string' }] },
  event: [
    { listen: 'prerequest', script: { type: 'text/javascript', exec: PRE_REQUEST } },
    { listen: 'test', script: { type: 'text/javascript', exec: AFTER_RESPONSE } },
  ],
  variable: Object.entries(VARIABLES).map(([key, value]) => ({ key, value, type: 'string' })),
  item: [...folders].map(([tag, items]) => ({ name: tag, item: items })),
};

const environment = {
  name: `${name} (local)`,
  values: Object.entries(VARIABLES)
    .filter(([key]) => !['accessToken', 'refreshToken'].includes(key))
    .map(([key, value]) => ({
      key,
      value,
      type: key === 'password' || key === 'apiKey' ? 'secret' : 'default',
      enabled: true,
    })),
  _postman_variable_scope: 'environment',
};

mkdirSync(outDir, { recursive: true });
const collectionFile = join(outDir, `${name}.postman_collection.json`);
const environmentFile = join(outDir, `${name}.local.postman_environment.json`);
writeFileSync(collectionFile, `${JSON.stringify(collection, null, 2)}\n`);
writeFileSync(environmentFile, `${JSON.stringify(environment, null, 2)}\n`);
const count = [...folders.values()].reduce((n, items) => n + items.length, 0);
console.log(`Wrote ${collectionFile} (${count} requests in ${folders.size} folders)`);
console.log(`Wrote ${environmentFile}`);
console.log('Postman: Import → both files; pick the environment; run Auth › Sign up or Sign in first.');
